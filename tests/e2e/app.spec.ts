import { test, expect, type Page } from '@playwright/test'
import { makeEPUB, makeMOBI, makePDF } from './fixtures'

const pageErrors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page }) => {
  const errors: string[] = []
  pageErrors.set(page, errors)
  page.on('pageerror', error => errors.push(error.message))
})
test.afterEach(async ({ page }) => { expect(pageErrors.get(page)).toEqual([]) })

async function upload(page: Page, name: string, buffer: Buffer) {
  await page.getByLabel('Chọn file sách', { exact: true }).setInputFiles({ name, mimeType: 'application/octet-stream', buffer })
  await expect(page.getByRole('heading', { name: 'Kết quả nhập sách' })).toBeVisible()
}
async function closeImport(page: Page) { await page.getByRole('button', { name: 'Về thư viện', exact: true }).click() }

test('EPUB: nhập, chống trùng, đọc, bookmark, highlight/ghi chú, phục hồi vị trí và offline', async ({ page, context }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Bắt đầu từ một cuốn sách' })).toBeVisible()
  await upload(page, 'sample.epub', makeEPUB())
  await expect(page.getByText('Đã thêm vào thư viện')).toBeVisible()
  await closeImport(page)
  await upload(page, 'renamed.epub', makeEPUB())
  await expect(page.getByText('Đã có trong thư viện')).toBeVisible()
  await closeImport(page)
  await page.getByRole('button', { name: 'Đọc Một khoảng lặng', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Thêm bookmark' })).toBeEnabled()
  await page.getByRole('button', { name: 'Trang sau', exact: true }).click()
  await page.getByRole('button', { name: 'Thêm bookmark', exact: true }).click()
  await page.getByRole('button', { name: 'Mục lục', exact: true }).click()
  await page.getByRole('button', { name: 'Những con đường', exact: true }).click()
  await expect(page.locator('.reader-progress > span')).toHaveText('Những con đường')
  // Book frames live in closed shadow roots; test data selection through the adapter's load document.
  const frame = page.frames().find(frame => frame.url().startsWith('blob:'))
  expect(frame).toBeTruthy()
  await frame!.waitForSelector('p')
  await frame!.evaluate(() => {
    const text = document.querySelector('p')!.firstChild!
    const range = document.createRange(); range.setStart(text, 0); range.setEnd(text, 30)
    const selection = getSelection()!; selection.removeAllRanges(); selection.addRange(range)
    document.dispatchEvent(new Event('selectionchange'))
  })
  await page.getByRole('button', { name: 'Ghi chú đoạn đã chọn', exact: true }).click()
  await page.getByPlaceholder('Điều bạn muốn ghi nhớ…').fill('Một ghi chú tiếng Việt')
  await page.getByRole('button', { name: 'Lưu ghi chú', exact: true }).click()
  await page.getByRole('button', { name: 'Bookmark và ghi chú', exact: true }).click()
  await expect(page.locator('.annotation').getByText('Một ghi chú tiếng Việt', { exact: true })).toBeVisible()
  await expect(page.locator('.annotation')).toHaveCount(2)
  await page.getByRole('button', { name: 'Đóng bảng', exact: true }).click()
  await page.getByRole('button', { name: 'Thiết lập đọc', exact: true }).click()
  await page.getByLabel('Cỡ chữ', { exact: true }).fill('24')
  await page.getByRole('button', { name: 'Đóng bảng', exact: true }).click()
  const progress = await page.getByRole('slider', { name: 'Tiến độ đọc' }).inputValue()
  await page.getByRole('button', { name: 'Về thư viện', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Đọc Một khoảng lặng', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Thêm bookmark' })).toBeEnabled()
  await expect(page.getByRole('slider', { name: 'Tiến độ đọc' })).toHaveValue(progress)
  await page.getByRole('button', { name: 'Về thư viện', exact: true }).click()
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Tất cả sách', exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Đọc Một khoảng lặng', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Thêm bookmark' })).toBeEnabled()
  expect(errors).toEqual([])
})

test('MOBI và PDF: đọc trực tiếp, PDF không có công cụ ghi chú', async ({ page, context }) => {
  await page.goto('/')
  await upload(page, 'sample.mobi', makeMOBI())
  await expect(page.getByText('Đã thêm vào thư viện')).toBeVisible()
  await closeImport(page)
  await page.getByRole('button', { name: 'Đọc Một ngày bình yên', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Thêm bookmark' })).toBeEnabled()
  await expect.poll(async () => page.frames().filter(f => f.url().startsWith('blob:')).length).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Trang sau', exact: true }).click()
  await page.getByRole('button', { name: 'Về thư viện', exact: true }).click()
  await upload(page, 'sample.pdf', makePDF())
  await closeImport(page)
  await page.getByRole('button', { name: 'Đọc PDF sample', exact: true }).click()
  await expect(page.locator('canvas').first()).toBeVisible()
  await expect.poll(async () => page.locator('canvas').first().evaluate(canvas => {
    const reader = document.querySelector('.reader-host')!.getBoundingClientRect()
    const rect = canvas.getBoundingClientRect()
    return rect.height <= reader.height + 1 && rect.width <= reader.width + 1
      && rect.left >= reader.left - 1 && rect.right <= reader.right + 1
      && rect.top >= reader.top - 1 && rect.bottom <= reader.bottom + 1
  })).toBe(true)
  await page.getByRole('button', { name: 'Trang sau', exact: true }).click()
  await expect(page.getByText('Trang 3 / 3', { exact: true }).or(page.getByText('Trang 2 / 3', { exact: true }))).toBeVisible()
  await page.getByRole('button', { name: 'Thêm bookmark' }).click()
  await page.getByRole('button', { name: 'Bookmark và ghi chú' }).click()
  await expect(page.locator('.annotation')).toHaveCount(1)
  await expect(page.getByRole('button', { name: 'Ghi chú vị trí hiện tại' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Đóng bảng' }).click()
  await page.getByRole('button', { name: 'Thiết lập đọc' }).click()
  await page.getByLabel('Cách đọc', { exact: true }).selectOption('scrolled')
  await page.getByRole('button', { name: 'Đóng bảng' }).click()
  await expect(page.locator('.page-slot')).toHaveCount(3)
  await page.getByRole('button', { name: 'Về thư viện', exact: true }).click()
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await context.setOffline(true)
  await page.reload()
  await page.getByRole('button', { name: 'Đọc PDF sample', exact: true }).click()
  await expect(page.locator('canvas').first()).toBeVisible()
  await expect(page.getByRole('button', { name: 'Thêm bookmark' })).toBeEnabled()
  await page.getByRole('button', { name: 'Về thư viện', exact: true }).click()
  await page.getByRole('button', { name: 'Đọc Một ngày bình yên', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Thêm bookmark' })).toBeEnabled()
})

