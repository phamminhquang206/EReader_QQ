test('nội dung sách không thực thi script hoặc gửi request bên ngoài', async ({ page }) => {
  const outgoing: string[] = []
  page.on('request', request => { if (request.url().startsWith('https://example.com')) outgoing.push(request.url()) })
  await page.goto('/')
  await upload(page, 'hostile.epub', makeEPUB(false, true))
  await closeImport(page)
  await page.getByRole('button', { name: 'Đọc Một khoảng lặng', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Thêm bookmark' })).toBeEnabled()
  expect(await page.evaluate(() => localStorage.getItem('book-script-ran'))).toBeNull()
  expect(outgoing).toEqual([])
})
